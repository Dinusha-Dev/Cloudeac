function ki_icon( $name, $class = '', $size = 24 ) {
	$paths = ki_icon_paths();
	if ( ! isset( $paths[ $name ] ) ) {
		return '';
	}
	$d    = $paths[ $name ];
	$fill = 0 === strpos( $d, 'fill:' );
	if ( $fill ) {
		$d = substr( $d, 5 );
	}
	$attrs = $fill
		? 'fill="currentColor"'
		: 'fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"';
	return sprintf(
		'<svg class="ico ico-%1$s %2$s" width="%3$d" height="%3$d" viewBox="0 0 24 24" %4$s aria-hidden="true" focusable="false"><path d="%5$s"/></svg>',
		esc_attr( $name ),
		esc_attr( $class ),
		(int) $size,
		$attrs, // phpcs:ignore WordPress.Security.EscapeOutput
		esc_attr( $d )
	);
}

function ki_the_icon( $name, $class = '', $size = 24 ) {
	echo ki_icon( $name, $class, $size ); // phpcs:ignore WordPress.Security.EscapeOutput
}
